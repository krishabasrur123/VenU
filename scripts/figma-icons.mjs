// Regenerates src/components/icons/figma-icons.ts from the SVGs exported from Figma into
// .kiro/figma/venu/svg. Icons drawn in one color use `currentColor`, so <FigmaIcon color=…> recolors them.
//
//   node scripts/figma-icons.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(ROOT, '.kiro/figma/venu/svg');
const OUT = join(ROOT, 'src/components/icons/figma-icons.ts');

// Friendly names for the icons screens use most. Every icon is also available by its file name.
const ALIASES = {
  'add-circle': 'add-circle-f1fa11', 'alert-triangle': 'alert-triangle-3c3d48', 'arrow-left': 'arrow-left-53079b',
  attachment: 'attachment-842b0c', caret: 'caret-90a693', 'checkbox-blank': 'check-box-outline-blank-1ffe1b',
  'check-circle': 'check-circle-febd77', clock: 'clock-8cfca4', door: 'iconixto-solid-door-1eccc0',
  'location-on': 'location-on-0007f2', 'map-pin': 'map-pin-44065e', person: 'person-805974', read: 'read-4b1a0c',
  record: 'record-7973f2', star: 'star-4acf9d', stickers: 'stickers-bba547', volume: 'volume-2-9f50a9',
  volunteer: 'volunteer-icon-4bc7ad', 'eye-off': 'vector-f55089', message: 'message-1-524926', 'message-unread': 'message-1-6cfb1c',
};

const colorsIn = svg => new Set([...svg.matchAll(/(?:fill|stroke)="(#[0-9A-Fa-f]{3,8}|black|white)"/g)].map(m => m[1].toLowerCase()));
function mono(svg) {
  const c = colorsIn(svg);
  if (c.size !== 1) return svg;
  const [only] = c;
  return svg.replace(new RegExp(`(fill|stroke)="${only.replace('#', '#?')}"`, 'gi'), '$1="currentColor"');
}
const clean = svg => svg.replace(/\r?\n/g, '').replace(/>\s+</g, '><').trim();

const icons = {};
for (const f of readdirSync(SRC).filter(f => f.endsWith('.svg')).sort()) icons[f.replace(/\.svg$/, '')] = clean(mono(readFileSync(join(SRC, f), 'utf8')));

// The Tab Bar's three icons come out of Figma as one 262x32 SVG; cut it into 32x32 icons.
const tab = readFileSync(join(SRC, 'frame-2275-957711.svg'), 'utf8');
const paths = [...tab.matchAll(/<path[^>]*\/>/g)].map(m => m[0]);
const cut = (x, ps) => clean(mono(`<svg width="32" height="32" viewBox="${x} 0 32 32" fill="none" xmlns="http://www.w3.org/2000/svg">${ps.join('')}</svg>`));
icons['tab-volunteer'] = cut(-0.75, paths.slice(0, 1));
icons['tab-venue'] = cut(120.25, paths.slice(1, 3));
icons['tab-profile'] = cut(235.25, paths.slice(3, 5));

for (const [alias, file] of Object.entries(ALIASES)) {
  if (!icons[file]) throw new Error(`alias ${alias}: no ${file}.svg`);
  icons[alias] = icons[file];
}

const body = Object.entries(icons).map(([k, v]) => `  '${k}': ${JSON.stringify(v)},`).join('\n');
writeFileSync(OUT, `// Generated by scripts/figma-icons.mjs from .kiro/figma/venu/svg. Don't edit by hand.\nexport const FIGMA_ICONS = {\n${body}\n} as const;\n\nexport type FigmaIconName = keyof typeof FIGMA_ICONS;\n`);
console.log(`${Object.keys(icons).length} icons -> ${OUT}`);
